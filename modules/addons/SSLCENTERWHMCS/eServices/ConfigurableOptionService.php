    public static function unassignFromProduct($productId, $name)
    {
        $optionGroup   = [
            'name'        => 'SSLCenter - ' . $name,
            'description' => 'Auto generated by module - SSLCenter #' . $productId
        ];
        
        $optionGroup = Capsule::table('tblproductconfiggroups')
                ->select('id')
                ->where('name', '=', $optionGroup['name'])
