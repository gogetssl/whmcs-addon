<?php

namespace MGModule\SSLCENTERWHMCS\eServices;

use Illuminate\Database\Capsule\Manager as Capsule;

class ConfigurableOptionService {

    /**
     * Code signing: "Certificate Delivery" dropdown with the provisioning methods of the API product.
     * Token shipping is charged once (setup fee, API shipping price x currency rate x price rate).
     * The administrator limits the methods by hiding sub-options in WHMCS.
     *
     * @param array|object $apiProduct API product (v1 shape with cs_methods / cs_shipping_options)
     */
    public static function createCodeSigningProvisioning($productId, $name, $apiProduct)
    {
        if (!is_null(self::getCodeSigningProvisioning($productId))) {
            return;
        }

        $methods = self::toArray(self::readValue($apiProduct, ['cs_methods']));
        if (empty($methods)) {
            $methods = \MGModule\SSLCENTERWHMCS\eHelpers\CodeSigningProduct::METHODS;
        }
        // no shipping options from the API = no shipping price to charge: no "new token" choice
        $shippingOptions = self::toArray(self::readValue($apiProduct, ['cs_shipping_options']));

        $subOptions = [];
        if (in_array(\MGModule\SSLCENTERWHMCS\eHelpers\CodeSigningProduct::METHOD_SHIP_TOKEN, $methods, true)) {
            foreach ($shippingOptions as $shipping) {
                $shipping = self::toArray($shipping);
                $subOptions[] = [
                    'value' => 'ship-token:' . strtoupper((string) $shipping['id']),
                    'label' => 'New hardware token - ' . (!empty($shipping['label']) ? $shipping['label'] : ucfirst(strtolower($shipping['id'])) . ' Shipping'),
                    'price' => isset($shipping['selling']) ? (float) $shipping['selling'] : 0.0,
                ];
            }
        }
        if (in_array(\MGModule\SSLCENTERWHMCS\eHelpers\CodeSigningProduct::METHOD_EXISTING_TOKEN, $methods, true)) {
            $subOptions[] = ['value' => 'existing-token', 'label' => 'I already have a compatible hardware token', 'price' => 0.0];
        }
        if (in_array(\MGModule\SSLCENTERWHMCS\eHelpers\CodeSigningProduct::METHOD_HSM, $methods, true)) {
            $subOptions[] = ['value' => 'hsm', 'label' => 'My own HSM (I will provide a CSR)', 'price' => 0.0];
        }

        $optionGroupId = Capsule::table('tblproductconfiggroups')->insertGetId([
            'name'        => 'SSLCenter - ' . $name,
            'description' => 'Auto generated by module - SSLCenter #' . $productId,
        ]);
        Capsule::table('tblproductconfiglinks')->insert(['gid' => $optionGroupId, 'pid' => $productId]);

        $optionId = Capsule::table('tblproductconfigoptions')->insertGetId([
            'gid'        => $optionGroupId,
            'optionname' => \MGModule\SSLCENTERWHMCS\eHelpers\CodeSigningProduct::OPTION_PROVISIONING . '|Certificate Delivery',
            'optiontype' => 1,
            'qtyminimum' => 0,
            'qtymaximum' => 0,
            'order'      => 0,
            'hidden'     => 0,
        ]);

        $currencies = (new \MGModule\SSLCENTERWHMCS\models\productConfiguration\Repository())->getAllCurrencies();
        foreach ($subOptions as $sortOrder => $subOption) {
            $subId = Capsule::table('tblproductconfigoptionssub')->insertGetId([
                'configid'   => $optionId,
                'optionname' => $subOption['value'] . '|' . $subOption['label'],
                'sortorder'  => $sortOrder,
                'hidden'     => 0,
            ]);

            foreach ($currencies as $currency) {
                Capsule::table('tblpricing')->insert(array_merge(
                    ['type' => 'configoptions', 'currency' => $currency->id, 'relid' => $subId],
                    self::buildOneTimeFeePricing($subOption['price'], $currency)
                ));
            }
        }
    }

    public static function getCodeSigningProvisioning($productId)
    {
        return Capsule::table('tblproductconfiggroups')
                ->select(['tblproductconfigoptions.id', 'tblproductconfiggroups.id as groupid'])
                ->join('tblproductconfigoptions', 'tblproductconfigoptions.gid', '=', 'tblproductconfiggroups.id')
                ->join('tblproductconfiglinks', 'tblproductconfiglinks.gid', '=', 'tblproductconfiggroups.id')
                ->where('tblproductconfiglinks.pid', '=', (int) $productId)
                ->where('tblproductconfigoptions.optionname', 'LIKE', \MGModule\SSLCENTERWHMCS\eHelpers\CodeSigningProduct::OPTION_PROVISIONING . '%')
                ->first();
    }

    /**
     * Updates the token shipping fees of the "Certificate Delivery" option from the API prices (price updater cron).
     */
    public static function syncCodeSigningShippingPrices($productId, $apiProduct)
    {
        $option = self::getCodeSigningProvisioning($productId);
        if (is_null($option)) {
            return;
        }

        $prices = [];
        foreach (self::toArray(self::readValue($apiProduct, ['cs_shipping_options'])) as $shipping) {
            $shipping = self::toArray($shipping);
            if (!empty($shipping['id'])) {
                $prices['ship-token:' . strtoupper((string) $shipping['id'])] = isset($shipping['selling']) ? (float) $shipping['selling'] : 0.0;
            }
        }
        if (empty($prices)) {
            return;
        }

        $currencies = (new \MGModule\SSLCENTERWHMCS\models\productConfiguration\Repository())->getAllCurrencies();
        $subOptions = Capsule::table('tblproductconfigoptionssub')->where('configid', $option->id)->get(['id', 'optionname']);
        foreach ($subOptions as $subOption) {
            $value = strtolower(trim(explode('|', (string) $subOption->optionname, 2)[0]));
            $key   =strpos($value, 'ship-token:') === 0 ? 'ship-token:' . strtoupper(substr($value, strlen('ship-token:'))) : $value;
            if (!isset($prices[$key])) {
                continue;
            }
            foreach ($currencies as $currency) {
                Capsule::table('tblpricing')
                    ->where('type', 'configoptions')
                    ->where('relid', $subOption->id)
                    ->where('currency', $currency->id)
                    ->update(self::buildOneTimeFeePricing($prices[$key], $currency));
            }
        }
    }

    /**
     * A one-time fee in WHMCS configurable option pricing: setup fee on every billing cycle, no recurring price.
     */
    private static function buildOneTimeFeePricing($basePrice, $currency)
    {
        $currencyRate = ($currency->default == '1') ? 1 : (float) $currency->rate;
        if ($currencyRate <= 0) {
            $currencyRate = 1;
        }
        $fee = number_format((float) $basePrice * $currencyRate * self::getGlobalRate(), 2, '.', '');

        $pricing = [];
        foreach (['m', 'q', 's', 'a', 'b', 't'] as $prefix) {
            $pricing[$prefix . 'setupfee'] = $fee;
        }
        foreach (['monthly', 'quarterly', 'semiannually', 'annually', 'biennially', 'triennially'] as $cycle) {
            $pricing[$cycle] = '0.00';
        }

        return $pricing;
    }

    public static function createForProductWildcard($productId, $name, $apiProduct = null) {

